import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import config from '../config/approved-home-tailwind.mjs';

// Compile the approved design against its own palette, then scope every rule.
// Protected application surfaces retain their existing Tailwind theme/reset.
const scope = {
  postcssPlugin: 'approved-home-scope',
  OnceExit(root) {
    const animations = new Map();
    root.walkAtRules(/keyframes$/, (rule) => {
      animations.set(rule.params, `approved-${rule.params}`);
      rule.params = `approved-${rule.params}`;
    });
    root.walkDecls(/^(animation|animation-name)$/, (decl) => {
      decl.value = decl.value.replace(/[\w-]+/g, (name) => animations.get(name) ?? name);
    });
    root.walkRules((rule) => {
      let parent = rule.parent;
      while (parent) {
        if (parent.type === 'atrule' && /keyframes$/.test(parent.name)) return;
        parent = parent.parent;
      }
      rule.selectors = rule.selectors.flatMap((selector) => {
        if (selector.startsWith('html.reduce-motion')) {
          return selector.replace('html.reduce-motion', 'html.reduce-motion .approved-home');
        }
        if ([':root', 'html', ':host', 'body'].includes(selector)) return '.approved-home';
        if (selector === '*') return ['.approved-home', '.approved-home *'];
        return `.approved-home ${selector}`;
      });
    });
  },
};

const source = readFileSync('src/styles/approved-home.source.css', 'utf8');
const result = await postcss([tailwindcss(config), scope]).process(source, { from: undefined });
const accessibility = `
/* Match the approved page scrollbar and keep its cinematic chrome unobstructed. */
html:has(.approved-home)::-webkit-scrollbar { width: 10px; height: 10px; }
html:has(.approved-home)::-webkit-scrollbar-track { background: #090b0d; }
html:has(.approved-home)::-webkit-scrollbar-thumb { background: #242a31; border-radius: 999px; border: 2px solid #090b0d; }
body:has(.approved-home) #page-voice-reader-root,
body:has(.approved-home) button[aria-label="Open Devonn AI Chat"] { display: none; }
.approved-home { isolation: isolate; overflow-x: clip; }
.approved-home section { scroll-margin-top: 88px; }
.approved-home .approved-skip-link { position: fixed; top: -80px; left: 16px; z-index: 200; background: #090b0d; color: white; padding: 12px 16px; }
.approved-home .approved-skip-link:focus { top: 12px; }
`;
writeFileSync('src/styles/approved-home.css', `/* Generated by scripts/generate-approved-home-style.mjs. */\n${result.css}\n${accessibility}`);
console.log('Approved homepage styles generated with scoped reset, palette, and animations.');
